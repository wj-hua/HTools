private enum ToolLogoCache {
    /// static let 只初始化一次且线程安全，每个 Logo 只解析一次 SVG。
    private static let images: [Tool: NSImage] = Dictionary(
        uniqueKeysWithValues: Tool.allCases.map { ($0, render($0)) }
    )

    static func image(for tool: Tool) -> NSImage {
        images[tool]!
    }

    private static func render(_ tool: Tool) -> NSImage {
        let svg = #"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="64" height="64" fill="black" fill-rule="evenodd">"#
            + tool.logoPaths + "</svg>"
        let image = NSImage(data: Data(svg.utf8))
            ?? NSImage(systemSymbolName: "questionmark.square", accessibilityDescription: nil)!
        image.isTemplate = true
        return image
    }
}
